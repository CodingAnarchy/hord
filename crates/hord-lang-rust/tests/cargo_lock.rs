// ------------------------------------------------ real-lockfile proptests

/// A real lockfile with a set of uniquely named, source-bearing packages
/// removed as a new dependency would add them: the `[[package]]` block and
/// every `"name",` dependency line.
fn without(text: &str, names: &[&str]) -> String {
    let mut out = text.to_owned();
    for name in names {
        let start = out
            .find(&format!("[[package]]\nname = \"{name}\"\n"))
            .expect("package block");
        let end = out[start + 1..]
            .find("[[package]]")
            .map_or(out.len(), |i| start + 1 + i);
        out.replace_range(start..end, "");
        out = out.replace(&format!(" \"{name}\",\n"), "");
    }
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}

/// Names that occur once in the lockfile and are depended on by name only.
fn removable(text: &str) -> Vec<String> {
    let mut counts: BTreeMap<&str, usize> = BTreeMap::new();
    for line in text.lines() {
        if let Some(name) = line
            .strip_prefix("name = \"")
            .and_then(|l| l.strip_suffix('"'))
        {
            *counts.entry(name).or_default() += 1;
        }
    }
    counts
        .into_iter()
        .filter(|(name, n)| {
            *n == 1
                && text.contains(&format!(" \"{name}\",\n"))
                && !text.contains(&format!(" \"{name} "))
        })
        .map(|(name, _)| name.to_owned())
        .collect()
}

proptest! {
    #![proptest_config(ProptestConfig::with_cases(24))]

    /// Both sides of a real lockfile each add different dependencies (new
    /// `[[package]]` blocks plus entries in their dependents' lists). The
    /// merge must reproduce Cargo's own bytes, in either order.
    #[test]
    fn real_lockfile_concurrent_additions_reproduce_it(
        pick in any::<prop::sample::Index>(),
        a in any::<prop::sample::Index>(),
        b in any::<prop::sample::Index>(),
    ) {
        let fixtures = fixtures();
        let (name, full) = &fixtures[pick.index(fixtures.len())];
        let names = removable(full);
        prop_assume!(names.len() >= 2);
        let (x, y) = (&names[a.index(names.len())], &names[b.index(names.len())]);
        prop_assume!(x != y);
        // Removing one must not also edit the other's block.
        let block = |n: &str| {
            let start = full.find(&format!("[[package]]\nname = \"{n}\"\n")).unwrap();
            let end = full[start + 1..].find("[[package]]").map_or(full.len(), |i| start + 1 + i);
            full[start..end].to_owned()
        };
        prop_assume!(!block(x).contains(&format!(" \"{y}\",")));
        prop_assume!(!block(y).contains(&format!(" \"{x}\",")));
        let base = without(full, &[x, y]);
        let ours = without(full, &[y]);
        let theirs = without(full, &[x]);
        let merged = merge_both(&base, &ours, &theirs);
        prop_assert!(merged.as_ref() == Ok(full), "{name}: adding {x} and {y}");
    }
}

/// Small random lockfiles over a fixed package pool, for commutativity.
fn arb_lock() -> impl Strategy<Value = String> {
    const POOL: [(&str, &str); 6] = [
        ("anyhow", "1.0.0"),
        ("log", "0.4.0"),
        ("serde", "1.0.0"),
        ("serde", "1.0.1"),
        ("syn", "1.0.0"),
        ("syn", "2.0.0"),
    ];
    (
        prop::collection::vec(any::<bool>(), POOL.len()),
        prop::collection::vec(any::<bool>(), POOL.len()),
        prop::collection::vec(0u8..2, POOL.len()),
    )
        .prop_map(|(present, root_dep, checksum)| {
            let keep: Vec<usize> = (0..POOL.len()).filter(|&i| present[i]).collect();
            let root_deps: Vec<String> = keep
                .iter()
                .filter(|&&i| root_dep[i])
                .map(|&i| format!("{} {}", POOL[i].0, POOL[i].1))
                .collect();
            let root_deps: Vec<&str> = root_deps.iter().map(String::as_str).collect();
            let mut blocks = vec![root("app", &root_deps)];
            for i in keep {
                let (name, version) = POOL[i];
                let block = pkg(name, version, &[]);
                blocks.push(if checksum[i] == 0 {
                    block
                } else {
                    block.replace("checksum = \"0", "checksum = \"f")
                });
            }
            lockfile(&blocks)
        })
}

proptest! {
    #![proptest_config(ProptestConfig::with_cases(256))]

    #[test]
    fn merge_is_commutative(base in arb_lock(), ours in arb_lock(), theirs in arb_lock()) {
        // merge_both asserts commutativity of both results and conflicts.
        if let Ok(merged) = merge_both(&base, &ours, &theirs) {
            let tree = CargoLockAdapter.parse(merged.as_bytes()).expect("re-parses");
            let projected = CargoLockAdapter.project(&tree);
            prop_assert_eq!(projected.as_slice(), merged.as_bytes());
            // Idempotent: merging the result with itself changes nothing.
            prop_assert_eq!(merge(&merged, &merged, &merged).unwrap(), merged);
        }
    }

    #[test]
    fn one_sided_change_is_taken_verbatim(base in arb_lock(), ours in arb_lock()) {
        let canon = |s: &str| merge(s, s, s).unwrap();
        prop_assert_eq!(merge(&base, &ours, &base).unwrap(), canon(&ours));
        prop_assert_eq!(merge(&base, &base, &ours).unwrap(), canon(&ours));
    }
}
