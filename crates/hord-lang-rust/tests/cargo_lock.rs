#[test]
fn matches_only_cargo_lock() {
    let a = CargoLockAdapter;
    let path = |s| RepoPath::from_str(s).unwrap();
    assert!(a.matches(&path("Cargo.lock"), &[]));
    assert!(a.matches(&path("crates/foo/Cargo.lock"), &[]));
    assert!(!a.matches(&path("Cargo.toml"), &[]));
    assert!(!a.matches(&path("Cargo.lock.orig"), &[]));
    assert!(!a.matches(&path("cargo.lock"), &[]));
    assert!(!a.matches(&path("foo/Cargo.lock/x"), &[]));
    assert!(is_cargo_lock(&path("a/Cargo.lock")));
    // The generic TOML adapter still owns *.toml and not the lockfile.
    assert!(!TomlAdapter.matches(&path("Cargo.lock"), &[]));
    assert!(TomlAdapter.matches(&path("Cargo.toml"), &[]));
    // ADR 0013 amendment: its own language id, distinct from TOML's.
    assert_eq!(a.lang().as_str(), hord_lang_rust::CARGO_LOCK_LANG);
    assert_ne!(a.lang(), TomlAdapter.lang());
    assert!(a.is_definition(&NodeKind::new("table_array_element")));
}

#[test]
fn real_lockfiles_are_lossless() {
    for (name, text) in fixtures() {
        let tree = CargoLockAdapter.parse(text.as_bytes()).expect(&name);
        assert_eq!(
            CargoLockAdapter.project(&tree).as_slice(),
            text.as_bytes(),
            "lossless {name}"
        );
        tree.check_concat()
            .unwrap_or_else(|e| panic!("{name}: {e}"));
    }
}

#[test]
fn packages_are_named_by_package_id() {
    for (name, text) in fixtures() {
        let tree = CargoLockAdapter.parse(text.as_bytes()).expect(&name);
        let names = def_names(&tree, "table_array_element");
        let blocks = text.matches("[[package]]").count();
        assert_eq!(names.len(), blocks, "{name}: every package is named");
        let unique: BTreeSet<_> = names.iter().collect();
        assert_eq!(
            unique.len(),
            names.len(),
            "{name}: package names are unique"
        );
        assert!(names.iter().all(|n| n.starts_with("package::")));
    }
    let text = lockfile(&[root("app", &["serde"]), pkg("serde", "1.0.0", &[])]);
    let tree = CargoLockAdapter.parse(text.as_bytes()).unwrap();
    let packages = def_names(&tree, "table_array_element");
    assert!(packages.contains(&"package::serde".to_owned()));
    assert!(packages.contains(&"package::app".to_owned()));
    let pairs = def_names(&tree, "pair");
    assert!(pairs.contains(&"package::serde::checksum".to_owned()));
    // A second version lengthens both names to include the version.
    let text = lockfile(&[
        root("app", &["syn 1.0.0", "syn 2.0.0"]),
        pkg("syn", "1.0.0", &[]),
        pkg("syn", "2.0.0", &[]),
    ]);
    let tree = CargoLockAdapter.parse(text.as_bytes()).unwrap();
    let packages = def_names(&tree, "table_array_element");
    assert!(packages.contains(&"package::syn 1.0.0".to_owned()));
    assert!(packages.contains(&"package::syn 2.0.0".to_owned()));
}

#[test]
fn package_name_is_independent_of_position() {
    let one = lockfile(&[root("app", &["serde"]), pkg("serde", "1.0.0", &[])]);
    let two = lockfile(&[
        root("app", &["anyhow", "serde"]),
        pkg("anyhow", "1.0.0", &[]),
        pkg("serde", "1.0.0", &[]),
    ]);
    let serde_of = |text: &str| {
        let tree = CargoLockAdapter.parse(text.as_bytes()).unwrap();
        tree.iter()
            .find(|(_, n)| {
                n.name
                    .as_ref()
                    .is_some_and(|q| q.to_string() == "package::serde")
            })
            .map(|(_, n)| n.normalized)
            .expect("serde package")
    };
    // Same name and content, even though it moved from index 1 to index 2.
    assert_eq!(serde_of(&one), serde_of(&two));
}

#[test]
fn ambiguous_versions_are_named_with_source() {
    let git = "git+https://github.com/serde-rs/serde?branch=main#0123abcd";
    let text = format!(
        "{HEADER}[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \
         \"serde 1.0.0 ({REGISTRY})\",\n \"serde 1.0.0 (git+https://github.com/serde-rs/serde?branch=main)\",\n]\n\n\
         {}[[package]]\nname = \"serde\"\nversion = \"1.0.0\"\nsource = \"{git}\"\n",
        pkg("serde", "1.0.0", &[])
    );
    let tree = CargoLockAdapter.parse(text.as_bytes()).unwrap();
    let names = def_names(&tree, "table_array_element");
    assert!(names.contains(&format!("package::serde 1.0.0 {REGISTRY}")));
    assert!(names.contains(&format!("package::serde 1.0.0 {git}")));
    // Cargo's own spelling and order round-trip.
    assert_eq!(merge(&text, &text, &text).unwrap(), text);
}

