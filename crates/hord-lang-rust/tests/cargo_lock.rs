//! `Cargo.lock` bridge: adapter and merge (spec §4.4, §12 M3, ADR 0013).
//!
//! The M3 acceptance line "`Cargo.lock` concurrent dependency additions merge
//! cleanly" is `concurrent_dependency_additions_merge_cleanly` (table) and
//! `real_lockfile_concurrent_additions_reproduce_it` (proptest over the real
//! fixtures, which are cargo.git and hord lockfiles written by Cargo).

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::PathBuf;
use std::str::FromStr;

use hord_core::{NodeKind, RepoPath};
use hord_lang::{LangAdapter, NodeTree};
use hord_lang_rust::{
    CargoLockAdapter, CargoLockConflict, CargoLockMergeError, is_cargo_lock, merge_cargo_lock,
};
use hord_lang_toml::TomlAdapter;
use hord_lang_toml::merge::{ConflictKind, TomlConflict};
use proptest::prelude::*;

const REGISTRY: &str = "registry+https://github.com/rust-lang/crates.io-index";
const HEADER: &str = "# This file is automatically @generated by Cargo.\n\
                      # It is not intended for manual editing.\n\
                      version = 4\n\n";

fn fixtures() -> Vec<(String, String)> {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("testdata/lock");
    let mut out: Vec<_> = fs::read_dir(&dir)
        .expect("testdata/lock")
        .map(|e| e.expect("entry").path())
        .filter(|p| p.extension().is_some_and(|e| e == "lock"))
        .map(|p| {
            let name = p.file_name().unwrap().to_string_lossy().into_owned();
            (name, fs::read_to_string(&p).expect("read"))
        })
        .collect();
    out.sort();
    assert!(out.len() >= 3, "expected the real lockfile fixtures");
    out
}

fn merge(base: &str, ours: &str, theirs: &str) -> Result<String, CargoLockMergeError> {
    merge_cargo_lock(base.as_bytes(), ours.as_bytes(), theirs.as_bytes())
        .map(|b| String::from_utf8(b).expect("utf-8"))
}

/// Merge both ways and require the same answer (spec §11.1 commutativity).
fn merge_both(base: &str, ours: &str, theirs: &str) -> Result<String, Vec<CargoLockConflict>> {
    let a = merge(base, ours, theirs);
    let b = merge(base, theirs, ours);
    match (a, b) {
        (Ok(a), Ok(b)) => {
            assert_eq!(a, b, "merge is not commutative");
            Ok(a)
        }
        (Err(CargoLockMergeError::Conflict(a)), Err(CargoLockMergeError::Conflict(b))) => {
            assert_eq!(a, b, "conflicts are not commutative");
            Err(a)
        }
        (a, b) => panic!("asymmetric merge: {a:?} vs {b:?}"),
    }
}

/// A registry package block as Cargo writes it.
fn pkg(name: &str, version: &str, deps: &[&str]) -> String {
    let mut s = format!(
        "[[package]]\nname = \"{name}\"\nversion = \"{version}\"\nsource = \"{REGISTRY}\"\n\
         checksum = \"{:0>64}\"\n",
        format!("{name}{version}").len()
    );
    push_deps(&mut s, deps);
    s
}

/// A path (workspace) package block.
fn root(name: &str, deps: &[&str]) -> String {
    let mut s = format!("[[package]]\nname = \"{name}\"\nversion = \"0.1.0\"\n");
    push_deps(&mut s, deps);
    s
}

fn push_deps(s: &mut String, deps: &[&str]) {
    if !deps.is_empty() {
        s.push_str("dependencies = [\n");
        for d in deps {
            s.push_str(&format!(" \"{d}\",\n"));
        }
        s.push_str("]\n");
    }
    s.push('\n');
}

/// Join package blocks into a lockfile (Cargo drops the final blank line).
fn lockfile(blocks: &[String]) -> String {
    let mut s = format!("{HEADER}{}", blocks.concat());
    while s.ends_with("\n\n") {
        s.pop();
    }
    s
}

fn def_names(tree: &NodeTree, kind: &str) -> Vec<String> {
    tree.iter()
        .filter(|(_, n)| n.kind.as_str() == kind)
        .filter_map(|(_, n)| n.name.as_ref().map(ToString::to_string))
        .collect()
}

